class GraphEvaluator:
    """Evaluates Vector vs Graph vs Hybrid retrieval models."""

    def __init__(self, golden_path: Path = GOLDEN_PATH, settings: Optional[Settings] = None):
        self.golden_path = golden_path
        self.settings = settings or get_settings()
        self.dataset = self._load_dataset()
        self.graph_store = build_academic_knowledge_graph(self.settings)
        self.vector_store = QdrantVectorStore(self.settings)
        self.embedding_service = EmbeddingService(self.settings)
        self.retriever = GraphRetriever(
            settings=self.settings,
            vector_store=self.vector_store,
            embedding_service=self.embedding_service,
            graph_store=self.graph_store
        )
        self._query_cache: Dict[str, List[float]] = {}

    def _load_dataset(self) -> List[Dict[str, Any]]:
        items = []
        with open(self.golden_path, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    items.append(json.loads(line))
        return items

    def precompute_embeddings(self) -> None:
        """Pre-embed all golden questions in batched calls."""
        unique_queries = list({it["question"] for it in self.dataset if it["question"] not in self._query_cache})
        if unique_queries:
            print(f"Pre-computing embeddings for {len(unique_queries)} queries in batches...", flush=True)
            vectors = self.embedding_service.embed_documents(unique_queries)
            for q, v in zip(unique_queries, vectors):
                self._query_cache[q] = v

    def evaluate_mode(
        self,
        mode: str,
        collection_name: str = "eval_retrieval_c500_o100",
        items_filter: Optional[str] = None
    ) -> Dict[str, float]:
        """Evaluate a retrieval mode on all items or filtered subset (e.g. multi-hop)."""
        self.precompute_embeddings()
        target_items = [
            it for it in self.dataset
            if len(it.get("gold_pages", [])) > 0 and (items_filter is None or it.get("type") == items_filter)
        ]

        if not target_items:
            return {}

        recalls_1, recalls_3, recalls_5 = [], [], []
        precs_1, precs_3, precs_5 = [], [], []
        hits_1, hits_3, hits_5 = [], [], []
        mrrs, ndcgs_3 = [], []
        latencies = []

        print(f"Evaluating mode '{mode}' on {len(target_items)} items (filter={items_filter})...", flush=True)

        for item in target_items:
            q = item["question"]
            gold_pages = item["gold_pages"]
            q_vec = self._query_cache.get(q)

            sources, _, lat_ms = self.retriever.retrieve(
                query=q,
                top_k=5,
                mode=mode,
                collection_name=collection_name,
                query_vector=q_vec
            )
            latencies.append(lat_ms)
            retrieved_pages = [s.page_number for s in sources]

            recalls_1.append(calculate_recall_at_k(retrieved_pages, gold_pages, 1))
            recalls_3.append(calculate_recall_at_k(retrieved_pages, gold_pages, 3))
            recalls_5.append(calculate_recall_at_k(retrieved_pages, gold_pages, 5))

            precs_1.append(calculate_precision_at_k(retrieved_pages, gold_pages, 1))
            precs_3.append(calculate_precision_at_k(retrieved_pages, gold_pages, 3))
            precs_5.append(calculate_precision_at_k(retrieved_pages, gold_pages, 5))

            hits_1.append(calculate_hit_at_k(retrieved_pages, gold_pages, 1))
            hits_3.append(calculate_hit_at_k(retrieved_pages, gold_pages, 3))
            hits_5.append(calculate_hit_at_k(retrieved_pages, gold_pages, 5))

            mrrs.append(calculate_mrr(retrieved_pages, gold_pages))
            ndcgs_3.append(calculate_ndcg_at_k(retrieved_pages, gold_pages, 3))

        return {
            "recall_at_1": round(float(np.mean(recalls_1)), 4),
            "recall_at_3": round(float(np.mean(recalls_3)), 4),
            "recall_at_5": round(float(np.mean(recalls_5)), 4),
            "precision_at_3": round(float(np.mean(precs_3)), 4),
            "hit_at_1": round(float(np.mean(hits_1)), 4),
            "hit_at_3": round(float(np.mean(hits_3)), 4),
            "mrr": round(float(np.mean(mrrs)), 4),
            "ndcg_at_3": round(float(np.mean(ndcgs_3)), 4),
            "latency_ms": round(float(np.mean(latencies)), 2)
        }

    def evaluate_triple_precision(self) -> Dict[str, Any]:
        """Compute precision over verified triples in graph_triples_check.jsonl."""
        if not TRIPLES_CHECK_PATH.exists():
            return {"status": "skipped", "reason": "graph_triples_check.jsonl not found"}

        labeled_triples = []
        with open(TRIPLES_CHECK_PATH, "r", encoding="utf-8") as f:
            for line in f:
                if line.strip():
                    labeled_triples.append(json.loads(line))

        if not labeled_triples:
            return {"status": "skipped", "reason": "No triples in file"}

        total = len(labeled_triples)
        valid = sum(1 for t in labeled_triples if t.get("human_valid") == 1)
        precision = round(valid / total, 4) if total > 0 else 0.0

        return {
            "status": "evaluated",
            "total_triples_checked": total,
            "valid_triples": valid,
            "triple_precision": precision
        }

    def run_comparative_benchmark(
        self,
        collection_name: str = "eval_retrieval_c500_o100"
    ) -> Dict[str, Any]:
        """Run full comparative benchmark across Vector, Graph, and Hybrid modes."""
        modes = ["vector", "graph", "hybrid"]
        all_results = {}
        multihop_results = {}

        for m in modes:
            all_results[m] = self.evaluate_mode(m, collection_name=collection_name, items_filter=None)
            multihop_results[m] = self.evaluate_mode(m, collection_name=collection_name, items_filter="multi-hop")

        triple_eval = self.evaluate_triple_precision()
        graph_stats = self.graph_store.stats()

        # Render Graph Visualization
        vis_path = export_graph_visualization(self.graph_store)

        return {
            "graph_topology": graph_stats,
            "overall_retrieval": all_results,
            "multihop_retrieval": multihop_results,
            "triple_precision": triple_eval,
            "visualization_image": str(vis_path)
        }


